/**
 * Site locales.
 *
 * Simplified Chinese is the root locale and also owns the engineering
 * documents (design, plan, ADRs, runbooks). Those are working documents rather
 * than product pages, so every locale links to them at their root paths and
 * labels them as Simplified Chinese instead of shipping stale translations.
 */
